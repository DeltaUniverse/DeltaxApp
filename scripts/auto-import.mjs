#!/usr/bin/env node

/**
 * Auto-import generator for Telegram Bot Modules.
 * Automatically discovers all module classes in src/modules/ (including subdirectories)
 * and generates src/modules/index.ts
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const MODULES_DIR = path.resolve(__dirname, '../src/modules');
const OUTPUT_FILE = path.resolve(MODULES_DIR, 'index.ts');

function toPascalCase(str) {
  return str
    .replace(/[-_]([a-z])/g, (_, letter) => letter.toUpperCase())
    .replace(/^[a-z]/, (letter) => letter.toUpperCase());
}

/**
 * Recursively find all TypeScript module files inside a directory
 */
function findModuleFiles(dir, subDir = '') {
  const currentDir = path.join(dir, subDir);
  if (!fs.existsSync(currentDir)) return [];

  const entries = fs.readdirSync(currentDir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const relativePath = subDir ? path.posix.join(subDir, entry.name) : entry.name;

    // Ignore hidden files and directories, index.ts, declaration files, and test files
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;

    if (entry.isDirectory()) {
      files.push(...findModuleFiles(dir, relativePath));
    } else if (
      entry.isFile() &&
      entry.name.endsWith('.ts') &&
      entry.name !== 'index.ts' &&
      !entry.name.endsWith('.d.ts') &&
      !entry.name.endsWith('.test.ts') &&
      !entry.name.endsWith('.spec.ts')
    ) {
      files.push(relativePath);
    }
  }

  return files.sort();
}

function scanModules() {
  if (!fs.existsSync(MODULES_DIR)) {
    fs.mkdirSync(MODULES_DIR, { recursive: true });
  }

  const moduleFiles = findModuleFiles(MODULES_DIR);

  const imports = [];
  const registeredClasses = [];

  for (const relativeFile of moduleFiles) {
    const fullPath = path.join(MODULES_DIR, relativeFile);
    const ext = path.extname(relativeFile);
    const pathWithoutExt = relativeFile.slice(0, -ext.length);
    const importPath = `./${pathWithoutExt.split(path.sep).join('/')}`;
    const baseName = path.basename(relativeFile, ext);

    if (!fs.existsSync(fullPath)) continue;
    let content;
    try {
      content = fs.readFileSync(fullPath, 'utf-8');
    } catch {
      continue;
    }

    // Look for exported classes extending BaseModule
    const classMatch = content.match(/export\s+class\s+([A-Za-z0-9_]+)\s+extends\s+BaseModule/);
    const defaultClassMatch = content.match(
      /export\s+default\s+class\s+([A-Za-z0-9_]+)\s+extends\s+BaseModule/
    );
    const defaultAnonMatch = content.match(/export\s+default\s+class\s+extends\s+BaseModule/);

    if (classMatch) {
      const className = classMatch[1];
      imports.push(`import { ${className} } from '${importPath}';`);
      registeredClasses.push(className);
    } else if (defaultClassMatch) {
      const className = defaultClassMatch[1];
      imports.push(`import ${className} from '${importPath}';`);
      registeredClasses.push(className);
    } else if (defaultAnonMatch) {
      const className = `${toPascalCase(baseName)}Module`;
      imports.push(`import ${className} from '${importPath}';`);
      registeredClasses.push(className);
    } else {
      // Fallback: check if any named export contains "Module"
      const anyModuleClass = content.match(/export\s+(?:default\s+)?class\s+([A-Za-z0-9_]*Module)/);
      if (anyModuleClass) {
        const className = anyModuleClass[1];
        imports.push(`import { ${className} } from '${importPath}';`);
        registeredClasses.push(className);
      } else {
        // Ignored non-module files silently or log info
      }
    }
  }

  const outputContent = `/**
 * =====================================================================
 * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY!
 * Generated by scripts/auto-import.mjs
 *
 * To add a new module, run:
 *   npm run make:module <name>
 * or create a new .ts file extending BaseModule in src/modules/.
 * =====================================================================
 */

import type { ModuleConstructor } from '../types';
${imports.join('\n')}

/**
 * Array of all auto-discovered module classes
 */
export const AUTO_MODULES: ModuleConstructor[] = [
  ${registeredClasses.map((cls) => `${cls},`).join('\n  ')}
];
`;

  // Only write if changed to avoid unnecessary re-triggers
  const existingContent = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf-8') : '';
  if (existingContent !== outputContent) {
    fs.writeFileSync(OUTPUT_FILE, outputContent, 'utf-8');
    console.log(
      `[Auto-Import] Successfully generated ${OUTPUT_FILE} with ${registeredClasses.length} module(s):`
    );
    for (const cls of registeredClasses) {
      console.log(`  -> ${cls}`);
    }
  } else {
    console.log(`[Auto-Import] Modules up to date (${registeredClasses.length} module(s)).`);
  }
}

// Run scanner immediately
scanModules();

// Check if --watch flag passed
if (process.argv.includes('--watch')) {
  console.log('[Auto-Import] Watching src/modules for changes (including subdirectories)...');
  let debounceTimeout = null;
  fs.watch(MODULES_DIR, { recursive: true }, (eventType, filename) => {
    if (filename && filename !== 'index.ts' && filename.endsWith('.ts')) {
      if (debounceTimeout) clearTimeout(debounceTimeout);
      debounceTimeout = setTimeout(() => {
        scanModules();
      }, 200);
    }
  });
}
